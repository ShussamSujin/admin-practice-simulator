// 각 항목: [항목명, [[값, 선택지?], ...], 비고?]  (항목명이 ''이면 값만 표시)

/** "사용 설정됨: '…'" ↔ "사용 중지됨: '…'" 반대 문구 페어를 만든다 */
function toggleOptions(value) {
  const v = String(value || '');
  if (v.startsWith('사용 설정됨: ')) return [v, `사용 중지됨: ${v.slice('사용 설정됨: '.length)}`, '사용자가 결정하도록 허용'];
  if (v.startsWith('사용 중지됨: ')) return [v, `사용 설정됨: ${v.slice('사용 중지됨: '.length)}`, '사용자가 결정하도록 허용'];
  return [v, '사용자가 결정하도록 허용'];
}

function renderItem(ctx, prefix, sectionName, uniq, [name, entries, note]) {
  const base = [prefix, sectionName, name].filter(Boolean).join(' · ');
  return `<div>
    ${name ? `<strong>${ctx.esc(name)}</strong>` : ''}
    ${entries.map(([value, options]) => ctx.editable({
      scope: `mobile:${ctx.currentOu()}`,
      name: uniq(base),
      value,
      options: options || toggleOptions(value),
      section: sectionName,
    })).join('')}
    ${note ? `<small class="field-help">${ctx.esc(note)}</small>` : ''}
  </div>`;
}

function renderSection(ctx, prefix, uniq, [name, desc, items]) {
  return `<article class="settings-card">
    <header><div><h2>${ctx.esc(name)}</h2>${desc ? `<p>${ctx.esc(desc)}</p>` : ''}</div>${ctx.icon('expand_more', 18)}</header>
    ${items && items.length ? `<div class="settings-card-grid">${items.map((item) => renderItem(ctx, prefix, name, uniq, item)).join('')}</div>` : ''}
    ${ctx.appliedOu()}
  </article>`;
}

/** 왼쪽 히어로 카드 + 오른쪽 섹션 카드 레이아웃 (dir-settings-layout 재사용) */
function settingsPage(ctx, { crumb, title, prefix, desc, sections }) {
  const seen = Object.create(null);
  const uniq = (base) => {
    seen[base] = (seen[base] || 0) + 1;
    return seen[base] === 1 ? base : `${base} · ${seen[base]}`;
  };
  return `<div class="section-page wide admin-page">
    ${ctx.crumb(crumb)}
    <div class="dir-settings-layout">
      <div class="dir-settings-hero">
        <div class="section-icon">${ctx.icon('devices', 26)}</div>
        <h1>${ctx.esc(title)}</h1>
        ${desc ? `<p class="page-desc">${ctx.esc(desc)}</p>` : ''}
      </div>
      <div class="settings-cards">
        ${sections.map((s) => renderSection(ctx, prefix, uniq, s)).join('')}
      </div>
    </div>
  </div>`;
}

